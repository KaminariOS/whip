import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { compile } from 'json-schema-to-typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const protocols = [17, 18, 19, 20];

const targets = [
  ['request', 'Request', 'Request'],
  ['success_response', 'SuccessResponse', 'Response'],
  ['error_response', 'ErrorResponse', 'Error'],
  ['event', 'EventEnvelope', 'Event'],
  ['subscription_event', 'SubscriptionEventEnvelope', 'SubscriptionEvent'],
];

const stale = [];

for (const protocol of protocols) {
  const relativeSchemaPath = `protocol/herdr-api-v${protocol}.schema.json`;
  const schemaPath = resolve(root, relativeSchemaPath);
  const document = JSON.parse(await readFile(schemaPath, 'utf8'));

  if (document.title !== 'Herdr API' || document.protocol !== protocol) {
    throw new Error(`${schemaPath} is not a Herdr API schema for protocol ${protocol}`);
  }

  const bannerComment = `/**
 * Generated from ${relativeSchemaPath} (Herdr protocol ${protocol}, schema ${document.schema_version}).
 * Do not edit this file directly. Run \`npm run generate:herdr-api\`.
 */`;

  for (const [schemaName, typeName, outputSuffix] of targets) {
    const schema = structuredClone(document.schemas?.[schemaName]);
    if (!schema) throw new Error(`Herdr API schema is missing schemas.${schemaName}`);

    localizeReferences(schema, schemaName);

    const generated = await compile(schema, typeName, {
      additionalProperties: false,
      bannerComment,
      style: {
        bracketSpacing: true,
        printWidth: 100,
        semi: true,
        singleQuote: true,
        tabWidth: 2,
        trailingComma: 'all',
        useTabs: false,
      },
      unreachableDefinitions: true,
    });
    await emit(`src/generated/herdrApiV${protocol}${outputSuffix}.ts`, generated);
  }
}

await emit('src/generated/herdrApi.ts', compatibilityModule());

if (stale.length > 0) {
  throw new Error(
    `Generated Herdr API types are stale:\n${stale.map(path => `  ${path}`).join('\n')}\n` +
      'Run `npm run generate:herdr-api`.',
  );
}

function localizeReferences(value, schemaName) {
  if (Array.isArray(value)) {
    value.forEach(item => localizeReferences(item, schemaName));
    return;
  }
  if (!value || typeof value !== 'object') return;

  const prefix = `#/schemas/${schemaName}/`;
  if (typeof value.$ref === 'string' && value.$ref.startsWith(prefix)) {
    value.$ref = `#/${value.$ref.slice(prefix.length)}`;
  }
  Object.values(value).forEach(item => localizeReferences(item, schemaName));
}

async function emit(relativeOutputPath, generated) {
  const outputPath = resolve(root, relativeOutputPath);
  if (check) {
    const current = await readFile(outputPath, 'utf8').catch(() => '');
    if (current !== generated) stale.push(relativeOutputPath);
  } else {
    await writeFile(outputPath, generated);
  }
}

function compatibilityModule() {
  const imports = protocols.flatMap(protocol => [
    `import type * as Request${protocol} from './herdrApiV${protocol}Request';`,
    `import type * as Response${protocol} from './herdrApiV${protocol}Response';`,
    `import type * as Error${protocol} from './herdrApiV${protocol}Error';`,
    `import type * as Event${protocol} from './herdrApiV${protocol}Event';`,
    `import type * as SubscriptionEvent${protocol} from './herdrApiV${protocol}SubscriptionEvent';`,
  ]).join('\n');
  const union = (moduleName, typeName) => protocols
    .map(protocol => `${moduleName}${protocol}.${typeName}`)
    .join(' | ');
  const byProtocol = (moduleName, typeName) => protocols
    .map((protocol, index) => (
      `${index === 0 ? '' : '  : '}Protocol extends ${protocol} ? ${moduleName}${protocol}.${typeName}`
    ))
    .join('\n');
  const aliases = [
    ['Request', 'Request'],
    ['Request', 'Subscription'],
    ['Response', 'ResponseResult'],
    ['Response', 'SessionSnapshot'],
    ['Response', 'SuccessResponse'],
    ['Response', 'AgentInfo'],
    ['Response', 'AgentSessionInfo'],
    ['Response', 'AgentStatus'],
    ['Response', 'PaneInfo'],
    ['Response', 'PaneLayoutPane'],
    ['Response', 'PaneLayoutRect'],
    ['Response', 'PaneLayoutSnapshot'],
    ['Response', 'PaneLayoutSplit'],
    ['Response', 'PaneScrollInfo'],
    ['Response', 'TabInfo'],
    ['Response', 'WorkspaceInfo'],
    ['Response', 'WorkspaceWorktreeInfo'],
    ['Error', 'ErrorBody'],
    ['Error', 'ErrorResponse'],
    ['Event', 'EventData'],
    ['Event', 'EventEnvelope'],
    ['Event', 'EventKind'],
    ['Event', 'WorktreeInfo'],
    ['SubscriptionEvent', 'SubscriptionEventData'],
    ['SubscriptionEvent', 'SubscriptionEventEnvelope'],
    ['SubscriptionEvent', 'SubscriptionEventKind'],
  ].map(([moduleName, typeName]) => (
    `export type ${typeName} = ${union(moduleName, typeName)};`
  )).join('\n');

  return `/**
 * Compatibility unions generated from every Herdr API protocol supported by Whip.
 * Do not edit this file directly. Run \`npm run generate:herdr-api\`.
 */
${imports}

export type SupportedHerdrProtocol = ${protocols.join(' | ')};
export type RequestForProtocol<Protocol extends SupportedHerdrProtocol> =
  ${byProtocol('Request', 'Request')}
  : never;
export type SubscriptionForProtocol<Protocol extends SupportedHerdrProtocol> =
  ${byProtocol('Request', 'Subscription')}
  : never;
export type ResponseResultForProtocol<Protocol extends SupportedHerdrProtocol> =
  ${byProtocol('Response', 'ResponseResult')}
  : never;
export type EventDataForProtocol<Protocol extends SupportedHerdrProtocol> =
  ${byProtocol('Event', 'EventData')}
  : never;
${aliases}
`;
}
